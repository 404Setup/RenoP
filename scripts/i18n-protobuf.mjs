import {createHash} from 'node:crypto';
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {brotliCompressSync} from 'node:zlib';

const requireUI = createRequire(new URL('../packages/renop-ui/package.json', import.meta.url));
const protobuf = requireUI('protobufjs');
const schemaURL = new URL('../proto/i18n/v1/catalog.proto', import.meta.url);
const root = protobuf.parse(readFileSync(schemaURL, 'utf8'), {keepCase: true}).root;
const KeyIndex = root.lookupType('renop.i18n.v1.KeyIndex');
const LocaleCatalog = root.lookupType('renop.i18n.v1.LocaleCatalog');

/** Hash canonical source bytes for immutable asset URLs and index compatibility. */
function digest(value) {
    return createHash('sha256').update(value).digest('hex');
}

/** Regenerate the shared browser decoder from the same schema used to encode assets. */
function generateDecoder() {
    const output = fileURLToPath(new URL('../packages/renop-ui/js/i18n.pb.js', import.meta.url));
    const cli = requireUI.resolve('protobufjs-cli/bin/pbjs');
    const result = spawnSync(process.execPath, [cli, '-t', 'static-module', '-w', 'es6', '--root', 'renop_i18n', '--keep-case',
        '--no-create', '--no-verify', '--no-delimited', '--no-typeurl', '--no-comments', '--no-service',
        '-o', output, fileURLToPath(schemaURL)], {stdio: 'inherit', windowsHide: true});
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error('Locale protobuf generation failed');
}

/** Merge validated dictionaries into one shared key index and one protobuf asset per language. */
export function generateLocaleAssets(catalogs, catalogFile) {
    const english = catalogs.get('en-US');
    if (!english) throw new Error('English locale is missing');
    const keys = Object.keys(english).sort();
    const revision = digest(JSON.stringify(keys));
    const assets = new Map();
    const add = (name, bytes) => {
        const path = `assets/i18n/${name}-${digest(bytes).slice(0, 20)}.pb`;
        assets.set(path, bytes);
        return '/' + path;
    };
    const index = add('keys', KeyIndex.encode({revision, keys}).finish());
    const locales = {};
    let jsonBytes = 0, jsonBrotli = 0;
    for (const [locale, entries] of [...catalogs].sort(([a], [b]) => a.localeCompare(b))) {
        if (Object.keys(entries).length !== keys.length || keys.some(key => typeof entries[key] !== 'string')) {
            throw new Error(`Invalid validated locale: ${locale}`);
        }
        locales[locale] = add(locale, LocaleCatalog.encode({
            locale,
            key_revision: revision,
            values: keys.map(key => entries[key])
        }).finish());
        const json = Buffer.from(JSON.stringify(entries));
        jsonBytes += json.length;
        jsonBrotli += brotliCompressSync(json).length;
    }
    generateDecoder();
    const source = `// Generated by scripts/i18n-protobuf.mjs. Do not edit.\n` +
        `import {createLocaleLoader} from '@renop/ui/i18n-catalog';\n` +
        `export const availableLocales = Object.freeze(${JSON.stringify(Object.keys(locales))});\n` +
        `export const loadLocale = createLocaleLoader(${JSON.stringify({index, revision, locales})});\n`;
    if (!existsSync(catalogFile) || readFileSync(catalogFile, 'utf8') !== source) writeFileSync(catalogFile, source);
    const bytes = [...assets.values()].reduce((total, data) => total + data.length, 0);
    const brotli = [...assets.values()].reduce((total, data) => total + brotliCompressSync(data).length, 0);
    console.log(`Locale assets: ${catalogs.size} languages; protobuf ${bytes} bytes (${brotli} Brotli), merged JSON ${jsonBytes} bytes (${jsonBrotli} Brotli).`);
    return assets;
}
